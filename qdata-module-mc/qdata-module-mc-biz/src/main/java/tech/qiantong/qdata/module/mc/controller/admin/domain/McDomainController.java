/**
 * Business domainController
 *
 * @author qdata
 * @date 2026-02-12
 */
@Tag(name = "业务域")
@RestController
@RequestMapping("/mc/domain")
@Validated
public class McDomainController extends BaseController {
    @Resource
    private IMcDomainService mcDomainService;

    @Operation(summary = "查询业务域列表")
    @GetMapping("/listpage")
    public CommonResult<PageResult<McDomainRespVO>> listpage(McDomainPageReqVO mcDomain) {
        PageResult<McDomainDO> page = mcDomainService.getMcDomainPage(mcDomain);
        return CommonResult.success(BeanUtils.toBean(page, McDomainRespVO.class));
    }

    @Operation(summary = "查询业务域列表")
    @GetMapping("/list")
    public CommonResult<List<McDomainRespVO>> list(McDomainPageReqVO mcDomain) {
        List<McDomainDO> mcDomainList = mcDomainService.getMcDomainList(mcDomain);
        return CommonResult.success(BeanUtils.toBean(mcDomainList, McDomainRespVO.class));
    }



    @Operation(summary = "导出业务域列表")
    @Log(title = "log.op.title.mc.domain", businessType = BusinessType.EXPORT)
    @PostMapping("/export")
    public void export(HttpServletResponse response, McDomainPageReqVO exportReqVO) {
        exportReqVO.setPageSize(PageParam.PAGE_SIZE_NONE);
        List<McDomainDO> list = (List<McDomainDO>) mcDomainService.getMcDomainPage(exportReqVO).getRows();
        ExcelUtil<McDomainRespVO> util = new ExcelUtil<>(McDomainRespVO.class);
        util.exportExcel(response, McDomainConvert.INSTANCE.convertToRespVOList(list), "Application Management Data");
    }

    @Operation(summary = "获取业务域详细信息")
    @GetMapping(value = "/{id}")
    public CommonResult<McDomainRespVO> getInfo(@PathVariable("id") Long id) {
        McDomainDO mcDomainDO = mcDomainService.getMcDomainById(id);
        return CommonResult.success(BeanUtils.toBean(mcDomainDO, McDomainRespVO.class));
    }

    @Operation(summary = "新增业务域")
    @Log(title = "log.op.title.mc.domain", businessType = BusinessType.INSERT)
    @PostMapping
    public CommonResult<Long> add(@Valid @RequestBody McDomainSaveReqVO mcDomain) {
        mcDomain.setCreatorId(getUserId());
        mcDomain.setCreateBy(getNickName());
        mcDomain.setCreateTime(DateUtil.date());
        return CommonResult.toAjax(mcDomainService.createMcDomain(mcDomain));
    }

    @Operation(summary = "修改业务域")
    @Log(title = "log.op.title.mc.domain", businessType = BusinessType.UPDATE)
    @PutMapping
    public CommonResult<Integer> edit(@Valid @RequestBody McDomainSaveReqVO mcDomain) {
        mcDomain.setUpdatorId(getUserId());
        mcDomain.setUpdateBy(getNickName());
        mcDomain.setUpdateTime(DateUtil.date());
        return CommonResult.toAjax(mcDomainService.updateMcDomain(mcDomain));
    }

    @Operation(summary = "删除业务域")
    @Log(title = "log.op.title.mc.domain", businessType = BusinessType.DELETE)
    @DeleteMapping("/{ids}")
    public CommonResult<Integer> remove(@PathVariable Long[] ids) {
        return CommonResult.toAjax(mcDomainService.removeMcDomain(Arrays.asList(ids)));
    }

    /**
     * Batch deletion check, query the number that can be deleted and the number that cannot be deleted
     */
    @Operation(summary = "批量删除检查业务域")
    @GetMapping("/batchDeleteCheck/{ids}")
    public CommonResult<BatchDeleteCheck<Long>> batchDeleteCheck(@PathVariable Long[] ids) {
        BatchDeleteCheck<Long> result = mcDomainService.batchDeleteCheck(Arrays.asList(ids));
        return CommonResult.success(result);
    }
}









































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































